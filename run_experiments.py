def _run_centralized(seed: int) -> dict:
    from training.utils import set_seed, resolve_device
    from training.train import train_model_ex
    from datasets.preprocessing import preprocess_dataset, get_n_features
    from datasets.cmapss_dataset import build_datasets, make_dataloader
    from models.lstm_model import build_model

    set_seed(seed)
    device = resolve_device(CFG.train.device)

    splits     = preprocess_dataset(dataset_id=DATASET_ID)
    n_features = get_n_features(DATASET_ID)

    train_ds, val_ds, test_ds = build_datasets(splits, rul_cap=RUL_CAP)
    train_ldr = make_dataloader(train_ds, batch_size=BATCH_SIZE, shuffle=True)
    val_ldr   = make_dataloader(val_ds,   batch_size=BATCH_SIZE, shuffle=False)
    test_ldr  = make_dataloader(test_ds,  batch_size=BATCH_SIZE, shuffle=False)

    model = build_model(input_size=n_features, hidden_size=HIDDEN_SIZE,
                        num_layers=NUM_LAYERS, dropout=DROPOUT, device=device)

    result = train_model_ex(
        model=model, train_loader=train_ldr, val_loader=val_ldr,
        test_loader=test_ldr, cfg=CFG.train, device=device,
        run_name=f"centralized_seed{seed}",
        checkpoint_dir=CFG.checkpoint_dir, log_dir=CFG.log_dir,
        rul_cap=RUL_CAP,
    )

    history = result["history"]
    val_losses = history.get("val_loss", [float("nan")])
    return {
        "seed":              seed,
        "rmse":              round(result["test_rmse"], 4),
        "mae":               round(result["test_mae"], 4),
        "nasa_score":        round(result["test_nasa_score"], 2),
        "training_time_s":   round(result["training_time_s"], 2),
        "inference_time_ms": round(result["inference_time_ms"], 6),
        "best_val_loss":     round(min(val_losses), 6),
        "final_val_loss":    round(val_losses[-1], 6),
        "num_epochs":        len(history.get("train_loss", [])),
        "best_epoch":        history.get("best_epoch", -1),
        "_history":          history,
    }


def exp_C_centralized():
    log.info("=" * 60)
    log.info("EXPERIMENT C -- Centralized Baseline")
    log.info("=" * 60)

    out_dir = os.path.join(RES, "centralized")
    mkdirs(out_dir)

    all_seeds_path = os.path.join(out_dir, "all_seeds.csv")
    summary_path   = os.path.join(out_dir, "summary.csv")
    if os.path.exists(all_seeds_path) and os.path.exists(summary_path):
        try:
            df_existing = pd.read_csv(all_seeds_path)
            if len(df_existing) == len(SEEDS) and not df_existing["rmse"].astype(str).str.contains(SENTINEL).any():
                log.info("  Reusing existing Centralized baseline results from %s", all_seeds_path)
                all_results = df_existing.to_dict(orient="records")
                summary_rows = pd.read_csv(summary_path).to_dict(orient="records")
                RESULTS_STORE["centralized"] = all_results
                RESULTS_STORE["centralized_summary"] = summary_rows
                log_experiment("Exp C -- Centralized (cached)", {"seeds": SEEDS}, [out_dir])
                log.info("Exp C DONE.\n")
                return all_results
        except Exception as e:
            log.warning("Could not load existing centralized results: %s. Re-running...", e)

    all_results = []
    for seed in SEEDS:
        log.info("  Centralized seed=%d ...", seed)
        res = safe_run(f"centralized_seed{seed}", _run_centralized, seed)
        if res == SENTINEL:
            all_results.append({"seed": seed, "rmse": SENTINEL,
                                 "mae": SENTINEL, "nasa_score": SENTINEL,
                                 "training_time_s": SENTINEL})
            continue

        hist = res["_history"]
        rows = [{"epoch": i+1, "train_loss": hist["train_loss"][i],
                 "val_loss": hist["val_loss"][i],
                 "val_rmse": hist.get("val_rmse", [float("nan")])[i],
                 "val_mae":  hist.get("val_mae",  [float("nan")])[i]}
                for i in range(len(hist.get("train_loss", [])))]
        _to_csv(pd.DataFrame(rows),
                os.path.join(out_dir, f"seed_{seed}_history.csv"))

        plain = {k: v for k, v in res.items() if not k.startswith("_")}
        all_results.append(plain)
        _to_csv(pd.DataFrame([plain]), os.path.join(out_dir, f"seed_{seed}.csv"))

    df_all = pd.DataFrame(all_results)
    summary_rows = []
    for metric in ["rmse", "mae", "nasa_score"]:
        vals = pd.to_numeric(df_all[metric], errors="coerce").dropna()
        summary_rows.append({
            "metric": metric,
            "mean": round(vals.mean(), 4) if len(vals) else SENTINEL,
            "std":  round(vals.std(),  4) if len(vals) else SENTINEL,
            "min":  round(vals.min(),  4) if len(vals) else SENTINEL,
            "max":  round(vals.max(),  4) if len(vals) else SENTINEL,
        })
    _to_csv(df_all, os.path.join(out_dir, "all_seeds.csv"))
    _to_csv(pd.DataFrame(summary_rows), os.path.join(out_dir, "summary.csv"))

    RESULTS_STORE["centralized"] = all_results
    RESULTS_STORE["centralized_summary"] = summary_rows
    log_experiment("Exp C -- Centralized", {"seeds": SEEDS}, [out_dir])
    log.info("Exp C DONE.\n")
    return all_results


