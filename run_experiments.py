def pareto_analysis():
    log.info("=" * 60)
    log.info("STEP 16 -- Pareto / Trade-Off Analysis")
    log.info("=" * 60)

    out_dir = os.path.join(RES, "tradeoff")
    mkdirs(out_dir)

    master = RESULTS_STORE.get("master", [])
    if not master:
        log.warning("No master results yet -- skipping Pareto."); return

    df = pd.DataFrame(master)
    for col in ["rmse_num", "comm_num", "time_num", "mae_num", "nasa_num"]:
        src = {"rmse_num":"rmse","comm_num":"communication_MB",
               "time_num":"training_time_s","mae_num":"mae","nasa_num":"nasa_score"}[col]
        df[col] = pd.to_numeric(df.get(src, float("nan")), errors="coerce")

    clean = df.dropna(subset=["rmse_num", "comm_num"]).copy()

    pareto_flags = []
    for i, row in clean.iterrows():
        dominated = any(
            (other["rmse_num"] <= row["rmse_num"] and
             other["comm_num"] <= row["comm_num"] and
             (other["rmse_num"] < row["rmse_num"] or other["comm_num"] < row["comm_num"]))
            for j, other in clean.iterrows() if i != j
        )
        pareto_flags.append(not dominated)
    clean["pareto_efficient"] = pareto_flags

    summary_rows = []
    if len(clean) > 0:
        for label, idx in [("Best RMSE", clean["rmse_num"].idxmin()),
                            ("Best MAE",  clean["mae_num"].idxmin()),
                            ("Best NASA Score", clean["nasa_num"].idxmin()),
                            ("Lowest Communication", clean["comm_num"].idxmin())]:
            row = clean.loc[idx]
            summary_rows.append({
                "criterion": label,
                "experiment": row.get("experiment", SENTINEL),
                "rmse": row.get("rmse_num", SENTINEL),
                "mae":  row.get("mae_num", SENTINEL),
                "nasa_score": row.get("nasa_num", SENTINEL),
                "communication_MB": row.get("comm_num", SENTINEL),
                "training_time_s": row.get("time_num", SENTINEL),
                "pareto_efficient": row.get("pareto_efficient", SENTINEL),
            })

        for _, row in clean[clean["pareto_efficient"]].iterrows():
            summary_rows.append({
                "criterion": "Pareto Efficient",
                "experiment": row.get("experiment", SENTINEL),
                "rmse": row.get("rmse_num", SENTINEL),
                "mae":  row.get("mae_num", SENTINEL),
                "nasa_score": row.get("nasa_num", SENTINEL),
                "communication_MB": row.get("comm_num", SENTINEL),
                "training_time_s": row.get("time_num", SENTINEL),
                "pareto_efficient": True,
            })

    path = os.path.join(out_dir, "pareto_summary.csv")
    _to_csv(pd.DataFrame(summary_rows), path)
    RESULTS_STORE["pareto"] = summary_rows
    log.info("Pareto analysis DONE.\n")
    return summary_rows


