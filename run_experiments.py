def safe_run(name: str, fn, *args, **kwargs):
    """Run fn; log error and return SENTINEL on failure."""
    try:
        return fn(*args, **kwargs)
    except Exception:
        tb = traceback.format_exc()
        log.error("[%s] FAILED:\n%s", name, tb)
        log_experiment(name, {}, [], error=tb)
        return SENTINEL


def _to_csv(df: pd.DataFrame, path: str):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    df.to_csv(path, index=False)
    log.info("Saved -> %s", path)


def _fl_rounds_df(res: dict) -> pd.DataFrame:
    """Convert strategy_history into a per-round DataFrame."""
    hist = res["strategy_history"]
    rounds   = hist.get("round", [])
    ev_loss  = hist.get("eval_loss", [float("nan")] * len(rounds))
    ev_rmse  = hist.get("eval_rmse", [float("nan")] * len(rounds))
    ev_mae   = hist.get("eval_mae", [float("nan")] * len(rounds))
    ev_nasa  = hist.get("eval_nasa_score", [float("nan")] * len(rounds))
    rt       = res.get("round_times_s", [float("nan")] * len(rounds))
    n = len(rounds)
    rows = []
    for i in range(n):
        rows.append({
            "round":        rounds[i] if i < len(rounds) else i + 1,
            "val_loss":     ev_loss[i] if i < len(ev_loss) else float("nan"),
            "rmse":         ev_rmse[i] if i < len(ev_rmse) else float("nan"),
            "mae":          ev_mae[i] if i < len(ev_mae) else float("nan"),
            "nasa_score":   ev_nasa[i] if i < len(ev_nasa) else float("nan"),
            "round_time_s": rt[i] if i < len(rt) else float("nan"),
        })
    return pd.DataFrame(rows)


def _comm_mb(R: int, P: int, K: int, b: int = 4) -> dict:
    """Compute communication estimate in MB. Formula: C_FL = 2*R*b*P*K"""
    dl    = R * b * P * K / (1024**2)
    ul    = R * b * P * K / (1024**2)
    total = dl + ul
    return {"download_MB": round(dl, 4), "upload_MB": round(ul, 4),
            "total_MB": round(total, 4), "total_GB": round(total / 1024, 6)}


def _model_params(model) -> int:
    return sum(p.numel() for p in model.parameters())


