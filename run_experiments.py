def exp_B_model_stats():
    log.info("=" * 60)
    log.info("EXPERIMENT B -- Model Statistics")
    log.info("=" * 60)

    from models.lstm_model import build_model
    from training.utils import resolve_device
    from datasets.preprocessing import get_n_features

    out_dir = os.path.join(RES, "model")
    mkdirs(out_dir)

    n_features = get_n_features(DATASET_ID)
    device = resolve_device(CFG.train.device)

    model = build_model(
        input_size=n_features, hidden_size=HIDDEN_SIZE,
        num_layers=NUM_LAYERS, dropout=DROPOUT, device=device,
    )

    total_params     = sum(p.numel() for p in model.parameters())
    trainable_params = sum(p.numel() for p in model.parameters() if p.requires_grad)
    non_trainable    = total_params - trainable_params
    fp32_mb          = total_params * 4 / (1024**2)
    fp16_mb          = total_params * 2 / (1024**2)

    dummy = torch.randn(BATCH_SIZE, WINDOW_SIZE, n_features).to(device)
    model.eval()
    N_WARMUP, N_BENCH = 5, 100
    with torch.no_grad():
        for _ in range(N_WARMUP):
            _ = model(dummy)
    if torch.cuda.is_available():
        torch.cuda.synchronize()
    t0 = time.perf_counter()
    with torch.no_grad():
        for _ in range(N_BENCH):
            _ = model(dummy)
    if torch.cuda.is_available():
        torch.cuda.synchronize()
    elapsed = time.perf_counter() - t0
    inf_ms = elapsed / (N_BENCH * BATCH_SIZE) * 1000.0

    stats = {
        "total_parameters":            total_params,
        "trainable_parameters":        trainable_params,
        "non_trainable_parameters":    non_trainable,
        "model_size_fp32_mb":          round(fp32_mb, 4),
        "model_size_fp16_mb":          round(fp16_mb, 4),
        "input_shape":                 f"(batch, {WINDOW_SIZE}, {n_features})",
        "output_shape":                "(batch,)",
        "inference_time_ms_per_sample":round(inf_ms, 6),
    }

    csv_path = os.path.join(out_dir, "model_statistics.csv")
    _to_csv(pd.DataFrame([stats]), csv_path)

    RESULTS_STORE["model_stats"] = stats
    log_experiment("Exp B -- Model Statistics", {}, [csv_path])
    log.info("Total params: %d  FP32: %.2f MB  Inf: %.4f ms/sample",
             total_params, fp32_mb, inf_ms)
    log.info("Exp B DONE.\n")
    return stats


