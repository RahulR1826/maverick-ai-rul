def _get_git_hash() -> str:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], cwd=ROOT, stderr=subprocess.DEVNULL
        ).decode().strip()[:12]
    except Exception:
        return "UNKNOWN"


def _sw_versions() -> str:
    py = sys.version.split()[0]
    pt = torch.__version__
    try:
        import flwr; fl_v = flwr.__version__
    except Exception:
        fl_v = "?"
    np_v = np.__version__
    import sklearn; sk_v = sklearn.__version__
    return f"Python={py} PyTorch={pt} Flower={fl_v} NumPy={np_v} sklearn={sk_v}"


def _hw_info() -> str:
    cpu = platform.processor() or platform.machine()
    gpu = "CPU-only"
    if torch.cuda.is_available():
        gpu = torch.cuda.get_device_name(0)
    return f"CPU={cpu} GPU={gpu}"


def init_experiment_log():
    os.makedirs(RES, exist_ok=True)
    now = datetime.now().isoformat(timespec="seconds")
    git = _get_git_hash()
    sw  = _sw_versions()
    hw  = _hw_info()
    header = (
        "# Experiment Log\n"
        f"Generated: {now}\n"
        f"Git commit: {git}\n"
        f"Software: {sw}\n"
        f"Hardware: {hw}\n\n---\n\n"
    )
    with open(EXPLOG_PATH, "w", encoding="utf-8") as f:
        f.write(header)
    log.info("Experiment log initialised -> %s", EXPLOG_PATH)


def log_experiment(name: str, config: dict, result_files: list,
                   error: Optional[str] = None, fix: Optional[str] = None):
    now = datetime.now().isoformat(timespec="seconds")
    lines = [
        f"## {name}",
        f"**Time:** {now}",
        f"**Git:** {_get_git_hash()}",
        f"**Config:** {config}",
        f"**Result files:** {result_files}",
    ]
    if error:
        lines.append(f"**ERROR:** {error}")
    if fix:
        lines.append(f"**Fix applied:** {fix}")
    lines.extend(["", "---", ""])
    with open(EXPLOG_PATH, "a", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


