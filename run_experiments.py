def exp_J_engine_level():
    log.info("=" * 60)
    log.info("EXPERIMENT J -- Engine-Level Client Ownership")
    log.info("=" * 60)

    from federated.simulation import run_federated_simulation_ex
    from datasets.preprocessing import (
        load_raw, compute_rul, get_feature_columns, apply_scaler,
    )
    from datasets.split_clients import engine_split, get_engine_splits, get_engine_labels
    import joblib as _jl

    out_dir = os.path.join(RES, "engine_level")
    mkdirs(out_dir)

    splits           = preprocess_dataset_once()
    X_train, y_train = splits["train"]

    # Rebuild engine labels
    train_raw = load_raw(DATASET_ID, "train", CFG.data_dir)
    train_raw = compute_rul(train_raw, RUL_CAP)
    feature_cols = get_feature_columns(train_raw, DROP_SENSORS)

    scaler_path = os.path.join(CFG.processed_dir, DATASET_ID, "scaler.joblib")
    scaler      = _jl.load(scaler_path)

    all_units = sorted(train_raw["unit"].unique())
    rng       = np.random.default_rng(PRIMARY_SEED)
    n_val     = max(1, int(len(all_units) * 0.10))
    val_units = set(rng.choice(all_units, size=n_val, replace=False).tolist())
    train_units = [u for u in all_units if u not in val_units]
    train_df    = train_raw[train_raw["unit"].isin(train_units)].copy()
    train_df_n  = apply_scaler(train_df, feature_cols, scaler)

    engine_labels = get_engine_labels(train_df_n, feature_cols, WINDOW_SIZE, STRIDE)

    n_engines_total = len(all_units)
    engine_ids_map  = get_engine_splits(n_engines_total, NUM_CLIENTS)

    # Align lengths if needed
    if len(engine_labels) != len(y_train):
        min_len = min(len(engine_labels), len(y_train))
        log.warning("Engine labels length mismatch (%d vs %d), trimming to %d",
                    len(engine_labels), len(y_train), min_len)
        engine_labels = engine_labels[:min_len]
        X_train_e = X_train[:min_len]; y_train_e = y_train[:min_len]
    else:
        X_train_e = X_train; y_train_e = y_train

    client_data = engine_split(X_train_e, y_train_e, engine_ids_map, engine_labels)

    # Multi-seed (S21)
    all_results     = []
    engine_log_rows = []
    for seed in SEEDS:
        log.info("  Engine-level seed=%d ...", seed)
        res = safe_run(f"engine_level_seed{seed}",
                       run_federated_simulation_ex,
                       num_clients=NUM_CLIENTS, num_rounds=NUM_ROUNDS,
                       local_epochs=LOCAL_EPOCHS, iid=True,
                       seed=seed, dataset_id=DATASET_ID,
                       run_name=f"engine_level_seed{seed}",
                       client_data_override=client_data,
                       engine_ids_per_client=engine_ids_map)

        if res == SENTINEL:
            all_results.append({"seed": seed, "test_rmse": SENTINEL}); continue

        df_rounds = _fl_rounds_df(res)
        _to_csv(df_rounds, os.path.join(out_dir, f"seed_{seed}_rounds.csv"))

        for cid, (X_c, y_c) in client_data.items():
            engine_log_rows.append({
                "client_id": cid,
                "engine_ids": str(engine_ids_map.get(cid, [])),
                "n_engines":  len(engine_ids_map.get(cid, [])),
                "n_windows":  len(y_c),
            })

        all_results.append({
            "seed":            seed,
            "test_rmse":       round(res["test_rmse"], 4),
            "test_mae":        round(res["test_mae"], 4),
            "test_nasa_score": round(res["test_nasa_score"], 2),
            "training_time_s": round(res["total_time_s"], 2),
        })

    _to_csv(pd.DataFrame(engine_log_rows).drop_duplicates(),
            os.path.join(out_dir, "client_engine_mapping.csv"))
    _to_csv(pd.DataFrame(all_results), os.path.join(out_dir, "summary.csv"))

    RESULTS_STORE["engine_level"] = all_results
    log_experiment("Exp J -- Engine-Level", {}, [out_dir])
    log.info("Exp J DONE.\n")
    return all_results


