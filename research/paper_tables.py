"""
research/paper_tables.py
------------------------
Manuscript-ready tables (mean ± SD over seeds) and a placeholder → value map
replacing section 14 of the old ``results/FINAL_REPORT.md``.  Generated only
from ``tables/summary.csv``.

python -m research.paper_tables [--out results/v2]
"""

import argparse
import os
import sys

import pandas as pd

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if ROOT not in sys.path:
    sys.path.insert(0, ROOT)
from research import config as C


def pm(r, m, d=2):
    return f"{r[m + '_mean']:.{d}f} ± {r[m + '_std']:.{d}f}"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=C.DEFAULT_OUT_DIR)
    a = ap.parse_args(argv)
    s = pd.read_csv(os.path.join(a.out, "tables", "summary.csv"))
    od = os.path.join(a.out, "paper_tables")
    os.makedirs(od, exist_ok=True)

    def get(exp, grid="default", ck="selected"):
        r = s[(s.experiment == exp) & (s.grid_label == grid) & (s.checkpoint == ck)]
        if len(r) != 1:
            raise KeyError((exp, grid, ck))
        return r.iloc[0]

    def rows(spec, ck):
        out = []
        for label, exp, grid in spec:
            r = get(exp, grid, ck)
            out.append({"Configuration": label, "n_seeds": int(r.n_seeds), "RMSE": pm(r, "rmse"), "MAE": pm(r, "mae"),
                        "NASA score": pm(r, "nasa_score", 1), "Traffic (MB, payload est.)": f"{r.comm_total_MB_mean:.1f}"})
        return pd.DataFrame(out)

    main_spec = [("Centralized (budget-matched)", "centralized", "default"),
                 ("Centralized (original early stopping)", "centralized_legacy_es", "default"),
                 ("FedAvg IID-window (K=5)", "fedavg_iid", "default"),
                 ("Local-only IID-window (mean of 5)", "local_iid", "default"),
                 ("FedAvg whole-engine (K=5)", "fedavg_engine", "default"),
                 ("Local-only whole-engine (mean of 5)", "local_engine", "default"),
                 ("Ablation: FedAvg K=1 (optimizer reset only)", "ablation_fedavg_k1", "default")]
    part_spec = [("IID window", "fedavg_iid", "default"),
                 ("Dirichlet α=1.0", "fedavg_dirichlet", "dirichlet_alpha=1.0"),
                 ("Dirichlet α=0.5", "fedavg_dirichlet", "dirichlet_alpha=0.5"),
                 ("Dirichlet α=0.1", "fedavg_dirichlet", "dirichlet_alpha=0.1"),
                 ("Whole-engine", "fedavg_engine", "default")]
    sweeps = {"T3_rounds": [(f"R={v}", "sweep_rounds", f"num_rounds={v}") for v in (5, 10, 20, 30)],
              "T4_local_epochs": [(f"E={v}", "sweep_local_epochs", f"local_epochs={v}") for v in (1, 3, 5, 10)],
              "T5_clients_iid": [(f"K={v}", "sweep_clients", f"num_clients={v}") for v in (2, 5, 10)],
              "T6_clients_engine": [(f"K={v}", "sweep_clients_engine", f"num_clients={v}") for v in (2, 5, 10)]}
    for ck in ("selected", "final"):
        rows(main_spec, ck).to_csv(os.path.join(od, f"T1_main_comparison_{ck}.csv"), index=False)
        rows(part_spec, ck).to_csv(os.path.join(od, f"T2_partitions_{ck}.csv"), index=False)
        for name, spec in sweeps.items():
            rows(spec, ck).to_csv(os.path.join(od, f"{name}_{ck}.csv"), index=False)

    v = lambda exp, grid="default", m="rmse", ck="selected", d=2: pm(get(exp, grid, ck), m, d)
    lines = ["# Manuscript values (v2 protocol, 5 seeds, mean ± SD)", "",
             "Replaces section 14 of `results/FINAL_REPORT.md`. Selected = validation-selected checkpoint "
             "(primary); final = model after the full budget (round sweep uses final). Generated by "
             "`python -m research.paper_tables`.", "", "```"]
    pairs = [("CENT_RMSE", v("centralized")), ("CENT_MAE", v("centralized", m="mae")),
             ("CENT_NASA", v("centralized", m="nasa_score", d=1)),
             ("FL_RMSE", v("fedavg_iid")), ("FL_MAE", v("fedavg_iid", m="mae")), ("FL_NASA", v("fedavg_iid", m="nasa_score", d=1)),
             ("LOCAL_IID_RMSE", v("local_iid")), ("LOCAL_ENGINE_RMSE", v("local_engine")),
             ("LOCAL_ENGINE_NASA", v("local_engine", m="nasa_score", d=1)),
             ("ENGINE_RMSE", v("fedavg_engine")), ("ENGINE_MAE", v("fedavg_engine", m="mae")),
             ("ENGINE_NASA", v("fedavg_engine", m="nasa_score", d=1)),
             ("ABLATION_K1_RMSE", v("ablation_fedavg_k1")),
             *[(f"R{r}_RMSE_final", v("sweep_rounds", f"num_rounds={r}", ck="final")) for r in (5, 10, 20, 30)],
             *[(f"E{e}_RMSE", v("sweep_local_epochs", f"local_epochs={e}")) for e in (1, 3, 5, 10)],
             *[(f"K{k}_RMSE", v("sweep_clients", f"num_clients={k}")) for k in (2, 5, 10)],
             *[(f"K{k}_ENGINE_RMSE", v("sweep_clients_engine", f"num_clients={k}")) for k in (2, 5, 10)],
             ("IID_RMSE", v("fedavg_iid")),
             *[(f"ALPHA_{str(al).replace('.', '')}_RMSE", v("fedavg_dirichlet", f"dirichlet_alpha={al}")) for al in (1.0, 0.5, 0.1)],
             *[(f"R{r}_COMM_MB", f"{get('sweep_rounds', f'num_rounds={r}').comm_total_MB_mean:.2f}") for r in (5, 10, 20, 30)],
             *[(f"K{k}_COMM_MB", f"{get('sweep_clients', f'num_clients={k}').comm_total_MB_mean:.2f}") for k in (2, 5, 10)],
             ("TOTAL_COMM_PRIMARY_MB", f"{get('fedavg_iid').comm_total_MB_mean:.2f}  (serialized-payload estimate; MB = 10^6 B)"),
             ("COMM_FORMULA", "C = 2 x K x R x S, S = 864,260 B measured serialized fp32 payload; no protocol overhead"),
             ("SEEDS", "42, 123, 2026, 3407, 9001 (matched across methods)")]
    lines += [f"[{k:22s}] = {val}" for k, val in pairs] + ["```", "",
              "Timing: use report section 8b (dedicated benchmark), not per-run wall times."]
    with open(os.path.join(od, "PAPER_VALUES.md"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    print("Paper tables ->", od)


if __name__ == "__main__":
    main()
